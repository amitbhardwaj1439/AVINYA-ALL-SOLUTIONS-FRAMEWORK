def _derive_site_id(lte_df, nr_cell_df, site_basic_df):
    """The bare site id, e.g. 'GOTR03', from whichever sheet carries it.

    Most circles name cells <CIRCLE>_<..>_<SITE><sector>_<..>, so segment 4
    minus the sector letter is the site ('RJ_E_F8_OM_GOTR03A_A' -> 'GOTR03'),
    and that is still tried first so those circles are unaffected.

    The VI circles name cells after the node instead ('LO01INMP606361F21'),
    which has no segments at all -- indexing segment 4 raised IndexError and
    failed the whole request before any circle-specific code ran. So the NR
    cell name, then Site_Basic's own 'Site ID', then the node name are tried in
    turn, and the id is simply left blank if nothing carries one (the zip name
    skips empty parts).
    """
    cells = (lte_df["eUtranCellFDDId"].dropna().astype(str)
             if "eUtranCellFDDId" in lte_df else [])
    for name in cells:
        parts = name.split("_")
        if len(parts) > 4 and parts[4][:-1]:
            return parts[4][:-1]

    nr_cells = (nr_cell_df["gUtranCell"].dropna().astype(str)
                if "gUtranCell" in nr_cell_df else [])
    for name in nr_cells:
        parts = name.split("_")
        # 'KK_5_EE_T1_OM_5_xxxxBL0305_A' -> second-to-last segment, whose
        # 'xxxx' is the template's filler
        if len(parts) >= 2 and parts[-2].lstrip("xX"):
            return parts[-2].lstrip("xX")

    # VI circles: the workbook's own site id is the right name for the output.
    if "Site ID" in site_basic_df:
        for value in site_basic_df["Site ID"].dropna().astype(str):
            if value.strip():
                return value.strip()

    for column, frame in (("gNodeBName", nr_cell_df), ("eNodeBName", site_basic_df)):
        if column not in frame:
            continue
        for node in frame[column].dropna().astype(str):
            # 'KK-NLBL0305-1' -> the middle chunk, minus the circle's 'NL'
            chunks = node.split("-")
            if len(chunks) >= 2 and chunks[1]:
                return (chunks[1][2:] if chunks[1][:2].isalpha() and len(chunks[1]) > 2
                        else chunks[1])
            if node.strip():
                return node.strip()

    return ""


def is_vi_circle(circle):
    """Whether ``circle`` is a Vodafone Idea variant, e.g. "DEL_Vi".

    Vi circles are named <BASE>_Vi, so the suffix is the test. Matching on
    the suffix rather than a hard-coded list means a new Vi circle picks up
    the Vi cell templates as soon as its branch exists.
    """
    return str(circle or "").strip().upper().endswith("_VI")


